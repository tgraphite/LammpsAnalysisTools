"""Static checks: docs/manual must match the code.

The parameter table in each manual is generated by lat.docs.render_param_table.
This test re-renders it and fails on any drift, so a manual cannot silently
document a flag that no longer exists (or miss a new one).
"""

from __future__ import annotations

from pathlib import Path

import pytest

from lat import __version__
from lat.config import load
from lat.docs import manual_for, render_param_table
from lat.modules import all_modules

REPO = Path(__file__).resolve().parents[2]
MANUAL_DIR = REPO / "docs" / "manual"
BEGIN = "<!-- lat:params:begin -->"
END = "<!-- lat:params:end -->"
PLOT_COMMANDS = ("plot1d", "plot2d")
MODULE_NAMES = sorted(all_modules())


@pytest.fixture(scope="module")
def cfg():
    return load(str(REPO / "config" / "lat.yaml"))


@pytest.fixture(scope="module")
def modules():
    return all_modules()


def test_docs_root_has_only_two_development_documents():
    files = sorted(p.name for p in (REPO / "docs").iterdir() if p.is_file())
    assert files == ["CHANGELOG.md", "MODULE_STATUS.md"], (
        f"docs/ must keep only CHANGELOG.md and MODULE_STATUS.md, found {files}"
    )


def test_every_module_has_a_manual(modules):
    missing = []
    for name, cls in modules.items():
        assert cls.help_doc == f"manual/{name}.md", (
            f"{name}: help_doc must be manual/{name}.md, got {cls.help_doc!r}"
        )
        if not (MANUAL_DIR / f"{name}.md").is_file():
            missing.append(name)
    assert not missing, f"modules without a manual: {missing}"


@pytest.mark.parametrize("name", MODULE_NAMES)
def test_manual_parameter_table_is_generated_from_code(name, cfg, modules):
    cls = modules[name]
    text = (MANUAL_DIR / f"{name}.md").read_text()
    assert BEGIN in text and END in text, f"{name}.md is missing the generated-block markers"
    block = text.split(BEGIN, 1)[1].split(END, 1)[0].strip()
    expected = render_param_table(cls, cfg)
    assert block == expected, (
        f"{name}.md parameter table is stale; regenerate it from lat.docs.render_param_table"
    )


@pytest.mark.parametrize("name", MODULE_NAMES)
def test_manual_mentions_every_flag(name, modules):
    cls = modules[name]
    text = (MANUAL_DIR / f"{name}.md").read_text()
    missing = [flag for p in cls.params for flag in p.flags if flag not in text]
    assert not missing, f"{name}.md does not mention flags: {missing}"


@pytest.mark.parametrize("name", MODULE_NAMES)
def test_manual_declares_the_module_outputs(name, modules):
    cls = modules[name]
    text = (MANUAL_DIR / f"{name}.md").read_text()
    missing = []
    for pattern in cls.outputs:
        needle = pattern.split("*", 1)[0] if "*" in pattern else pattern
        if needle not in text:
            missing.append(pattern)
    assert not missing, f"{name}.md does not list outputs: {missing}"


def test_manual_index_links_every_module(modules):
    index = (MANUAL_DIR / "README.md").read_text()
    missing = [name for name in modules if f"({name}.md)" not in index]
    assert not missing, f"docs/manual/README.md does not link: {missing}"
    for name in PLOT_COMMANDS:
        assert f"({name}.md)" in index, f"docs/manual/README.md does not link {name}"


def test_manual_files_are_all_indexed(modules):
    expected = set(modules) | set(PLOT_COMMANDS) | {"README", "common"}
    actual = {p.stem for p in MANUAL_DIR.glob("*.md")}
    assert actual == expected, (
        f"unexpected manual files: {sorted(actual - expected)}; "
        f"missing manual files: {sorted(expected - actual)}"
    )


def test_packaged_manuals_are_identical():
    docs = REPO / "docs" / "manual"
    bundled = REPO / "src" / "lat" / "data" / "manual"
    assert bundled.is_dir(), "src/lat/data/manual is missing; copy docs/manual into the package"
    for path in sorted(docs.glob("*.md")):
        other = bundled / path.name
        assert other.is_file(), f"packaged manual missing: {other}"
        assert path.read_text() == other.read_text(), (
            f"{path.name}: docs/manual and src/lat/data/manual differ"
        )
    extra = sorted(p.name for p in bundled.glob("*.md") if not (docs / p.name).is_file())
    assert not extra, f"packaged manuals without a docs/manual source: {extra}"


def test_manual_path_resolves_for_every_module():
    for name in MODULE_NAMES:
        assert manual_for(name) is not None, f"manual resolution failed for {name}"


def test_module_status_and_changelog_cover_the_release(modules):
    status = (REPO / "docs" / "MODULE_STATUS.md").read_text()
    changelog = (REPO / "docs" / "CHANGELOG.md").read_text()
    missing = [name for name in modules if f"| {name} |" not in status]
    assert not missing, f"MODULE_STATUS.md does not list: {missing}"
    assert f"## [{__version__}]" in changelog
    assert f"当前版本 {__version__}" in status


def test_no_stale_development_document_links():
    stale = ("MANUAL_ALGORITHMS", "MANUAL_TESTER", "docs/07_decision_log",
             "docs/09_test_campaign", "docs/11_examples_recheck")
    hits = []
    for root in (REPO / "src", REPO / "tests"):
        for path in root.rglob("*.py"):
            if path.name == "test_manuals.py":
                continue
            text = path.read_text()
            for token in stale:
                if token in text:
                    hits.append(f"{path.relative_to(REPO)}: {token}")
    assert not hits, "stale document references: " + ", ".join(hits)
